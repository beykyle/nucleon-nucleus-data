#!/usr/bin/env python3
"""Build the evaluated copies of the static corpora, and, with ``--elm``, re-correct ELM.

- **The static tabulated corpora** (``spec.TABULATED``) are never changed. Each one registered with an evaluated
  copy is copied to ``<corpus>_evaluated`` with the corrections applied (``author_errors.EVALUATED``); one not yet
  built (no ``data/<corpus>``) is skipped.
- **ELM**, only with ``--elm``, is corrected in place: each file, and its BibTeX, is read as it was at
  ``--baseline`` (a git revision from before the corrections), so ELM can be re-corrected after a rule changes. A
  file not in the baseline is left as it is. ELM's notebooks apply the same correction when they write
  (``serialize.write_sector``), so after rebuilding ELM from them, do not pass ``--elm``: it would replace the
  rebuild with the baseline's data.

Nothing is written until every file has been processed. sm3 is corrected when it is built; rebuild it, and the
manifests, afterwards::

    source scripts/setup_exfor_db.sh 2025
    uv run python scripts/apply_author_errors.py [--elm] [--dry-run] [--report docs/AUTHOR_ERRORS_DIFF.md]
    uv run python scripts/curate_sm3.py && uv run python scripts/build_manifests.py
"""

from __future__ import annotations

import argparse
import copy
import json
import re
import shutil
import subprocess
from pathlib import Path

import numpy as np

from nn_corpora import author_errors, spec

#: the last commit whose ELM data predates the author-error corrections
BASELINE = "8d2e300"

HEADER = """# Author-uncertainty corrections: per-record changes

Generated by `scripts/apply_author_errors.py`: every record the corrections of
[AUTHOR_UNCERTAINTIES.md](AUTHOR_UNCERTAINTIES.md) change or drop, in

{scope}
Columns:
- *change*: `table` = values and errors replaced by the authors' tabulation; `errors` = per-point uncertainties
  and/or normalisation changed; **dropped** = the record is removed.
- *median error*: relative (%) for cross sections, absolute for analysing powers (Ay).
- *norm*: the fractional normalisation uncertainty (`systematic_normalization_error`), where it changed.

Totals: {totals}.

"""


def rel(d):
    y, e = np.abs(np.asarray(d["y"], float)), np.asarray(d["y_err"], float)
    return np.where(y > 0, e / np.where(y > 0, y, 1), np.nan)


def baseline_text(path: Path, ref: str) -> str | None:
    """The file as it was at git revision ``ref``, or None if it was not there."""
    rel_path = path.resolve().relative_to(spec.DATA_DIR.parent.resolve())
    out = subprocess.run(["git", "show", f"{ref}:{rel_path.as_posix()}"], capture_output=True, text=True,
                         cwd=spec.DATA_DIR.parent)
    return None if out.returncode else out.stdout


def filter_bib(text: str, entries: set[str]) -> str:
    """The BibTeX entries whose key ends in ``_<EXFOR entry><3-digit subentry>``, for the given EXFOR entries."""
    blocks = [b if b.startswith("@") else "@" + b for b in text.strip().split("\n@") if b.strip()]
    keep = [b for b in blocks if (m := re.match(r"@\w+\{[^,]*_([A-Z0-9]{5})\d{3},", b)) and m.group(1) in entries]
    return "\n".join(keep) + "\n" if keep else ""


class Report:
    def __init__(self):
        self.lines = ["| corpus | sector | target | subentry | E (MeV) | change | points | median error before → after | norm |",
                      "|---|---|---|---|---|---|---|---|---|"]
        self.n = {"dropped": 0, "changed": 0, "unchanged": 0}

    def add(self, corpus, sector, before, after):
        row = [corpus, sector, before.get("target"), before["EXFORAccessionNumber"],
               f"{before.get('energy', float('nan')):g}"]
        if after is None:
            self.n["dropped"] += 1
            self.lines.append("| " + " | ".join(row + ["**dropped**", str(len(before["data"]["x"])), "", ""]) + " |")
            return
        b, c = before["data"], after["data"]
        if b == c:
            self.n["unchanged"] += 1
            return
        self.n["changed"] += 1
        ay = before.get("type") == "APower"
        f = (lambda d: np.nanmedian(np.asarray(d["y_err"], float))) if ay else (lambda d: np.nanmedian(rel(d)))
        fmt = (lambda v: f"{v:.3f}") if ay else (lambda v: f"{100 * v:.1f} %")
        what = "table" if len(b["x"]) != len(c["x"]) or b["y"] != c["y"] else "errors"
        norm = (f"{100 * b.get('systematic_normalization_error', 0):.1f} → "
                f"{100 * c.get('systematic_normalization_error', 0):.1f} %"
                if b.get("systematic_normalization_error") != c.get("systematic_normalization_error") else "")
        self.lines.append("| " + " | ".join(row + [what, f"{len(b['x'])} → {len(c['x'])}",
                                                f"{fmt(f(b))} → {fmt(f(c))}", norm]) + " |")


def correct_elm(baseline: str, report: Report, pending: dict) -> None:
    for sector_dir in sorted(p for p in (spec.DATA_DIR / "elm").iterdir() if p.is_dir()):
        kept_entries = set()
        for path in sorted(sector_dir.glob("*.json")):
            text = baseline_text(path, baseline)
            if text is None:
                print(f"{path.relative_to(spec.DATA_DIR)}: not in {baseline}, left as it is")
                kept_entries |= {r["EXFORAccessionNumber"][:5] for r in json.loads(path.read_text())}
                continue
            out = []
            for rec in json.loads(text):
                before = copy.deepcopy(rec)
                new = author_errors.correct(rec, "elm")
                report.add("elm", sector_dir.name, before, new)
                if new is not None:
                    out.append(new)
                    kept_entries.add(new["EXFORAccessionNumber"][:5])
            pending[path] = json.dumps(out, indent=4) + "\n"
        for bib in sector_dir.glob("*.bib"):
            text = baseline_text(bib, baseline)
            if text is not None:
                pending[bib] = filter_bib(text, kept_entries)


def evaluate_static(static: str, report: Report, pending: dict, replaced: list) -> None:
    """``data/<static>`` -> ``data/<static>_evaluated``: the same records, corrected."""
    evaluated = author_errors.EVALUATED[static]
    src_root, dst_root = spec.DATA_DIR / static, spec.DATA_DIR / evaluated
    if not src_root.is_dir():
        print(f"data/{static} not built yet: {evaluated} skipped")
        return
    replaced.append(dst_root)
    for sector_dir in sorted(p for p in src_root.iterdir() if p.is_dir()):
        kept_entries = set()
        for path in sorted(sector_dir.glob("*.json")):
            out = []
            for rec in json.loads(path.read_text()):
                before = copy.deepcopy(rec)
                rec["corpus"] = evaluated
                rec["notes"] = list(rec.get("notes") or []) + [f"derived from the {static} corpus"]
                new = author_errors.correct(rec, evaluated)
                after = None
                if new is not None:
                    out.append(new)
                    kept_entries.add(new["EXFORAccessionNumber"][:5])
                    after = new
                report.add(evaluated, sector_dir.name, before, after)
            if out:
                pending[dst_root / sector_dir.name / path.name] = json.dumps(out, indent=4) + "\n"
        for bib in sector_dir.glob("*.bib"):
            text = filter_bib(bib.read_text(), kept_entries)
            if text:
                pending[dst_root / sector_dir.name / bib.name] = text


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--report", type=Path)
    ap.add_argument("--elm", action="store_true",
                    help="also re-correct ELM in place from --baseline (overwrites data/elm)")
    ap.add_argument("--baseline", default=BASELINE, help="git revision of the uncorrected ELM data (default %(default)s)")
    a = ap.parse_args()

    report, pending, replaced = Report(), {}, []
    if a.elm:
        correct_elm(a.baseline, report, pending)
    for static in author_errors.EVALUATED:
        evaluate_static(static, report, pending, replaced)

    if not a.dry_run:
        for root in replaced:  # an evaluated corpus is rebuilt whole: no stale target files
            if root.exists():
                shutil.rmtree(root)
        for path, text in pending.items():
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    print(report.n)
    text = "\n".join(report.lines) + "\n"
    if a.report:
        n = report.n
        totals = f"{n['changed']} records changed, {n['dropped']} dropped, {n['unchanged']} unchanged"
        evaluated = ", ".join(f"**{e}**" for e in author_errors.EVALUATED.values())
        static = ", ".join(author_errors.EVALUATED)
        scope = [f"- {evaluated}, compared with the same record in the static corpus ({static}) it is derived from."]
        if a.elm:
            scope.insert(0, f"- **elm**, compared with the record as curated from EXFOR without them (git revision "
                            f"`{a.baseline}`); sm3 takes most of its records from ELM, so the same changes reach it;")
        a.report.write_text(HEADER.format(scope="\n".join(scope) + "\n", totals=totals) + text)
    else:
        print(text)


if __name__ == "__main__":
    main()
